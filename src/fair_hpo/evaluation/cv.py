from __future__ import annotations

from pathlib import Path

import pandas as pd
from sklearn.model_selection import StratifiedKFold


DATA_DIR = Path("data/raw")
SPLIT_DIR = Path("data/splits")


DATASETS = [
    "wdbc",
    "adult",
    "bank_marketing",
]


def load_dataset(name: str):
    """
    Load normalized features and target.
    """

    X_path = DATA_DIR / name / "features.csv"
    y_path = DATA_DIR / name / "target.csv"

    if not X_path.exists():
        raise FileNotFoundError(X_path)

    if not y_path.exists():
        raise FileNotFoundError(y_path)

    X = pd.read_csv(X_path)
    y = pd.read_csv(y_path).iloc[:, 0]

    return X, y


def load_outer_split(
    dataset_name: str,
    fold_id: int,
):
    """
    Load one previously generated outer split.

    The indices were generated by scripts/make_splits.py
    and must not be regenerated during an experiment.
    """

    train_path = (
        SPLIT_DIR
        / dataset_name
        / f"outer_fold_{fold_id}_train.csv"
    )

    test_path = (
        SPLIT_DIR
        / dataset_name
        / f"outer_fold_{fold_id}_test.csv"
    )

    if not train_path.exists():
        raise FileNotFoundError(train_path)

    if not test_path.exists():
        raise FileNotFoundError(test_path)

    train_idx = pd.read_csv(train_path)["index"].to_numpy()
    test_idx = pd.read_csv(test_path)["index"].to_numpy()

    return train_idx, test_idx


def make_inner_splits(
    X_train,
    y_train,
    n_splits: int = 3,
    random_state: int = 42,
):
    """
    Create inner CV splits using ONLY the outer training data.
    """

    splitter = StratifiedKFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=random_state,
    )

    return list(
        splitter.split(X_train, y_train)
    )


def get_outer_data(
    dataset_name: str,
    fold_id: int,
):
    """
    Load the dataset and return the raw outer train/test data.
    """

    X, y = load_dataset(dataset_name)

    train_idx, test_idx = load_outer_split(
        dataset_name,
        fold_id,
    )

    X_train = X.iloc[train_idx].copy()
    X_test = X.iloc[test_idx].copy()

    y_train = y.iloc[train_idx].copy()
    y_test = y.iloc[test_idx].copy()

    return (
        X_train,
        X_test,
        y_train,
        y_test,
    )


def get_inner_cv(
    X_train,
    y_train,
    random_state: int = 42,
):
    """
    Return the fixed 3-fold inner CV splits.
    """

    return make_inner_splits(
        X_train=X_train,
        y_train=y_train,
        n_splits=3,
        random_state=random_state,
    )